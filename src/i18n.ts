export function detectInitialLanguage(): AppLanguage {
  const browserLanguage = navigator.language?.toLowerCase() ?? "en";
  return browserLanguage.startsWith("de") ? "de" : "en";
}

export function isAppLanguage(value: string | null): value is AppLanguage {
  return value === "de" || value === "en";
}

export function t(lang: AppLanguage, key: string, params?: Record<string, string | number>): string {
  const fallback = translations.de[key] ?? key;
  const template = translations[lang][key] ?? fallback;
  if (!params) return template;

  return Object.entries(params).reduce((acc, [name, value]) => {
    return acc.split(`{${name}}`).join(String(value));
  }, template);
}
